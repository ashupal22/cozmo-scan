"""Write docs/benchmark_report.md from the result files in bench/results/, so every number in the report comes from a
committed file.

    python bench/benchmark_report.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "bench" / "results"
load = lambda name: json.loads((R / name).read_text())  # noqa: E731


def main():
    video = load("fix_loop/ablation_none_video_vs_lidar.json")        # the shipped video tier (fix off)
    photo = load("photo_vs_lidar.json")
    planes = load("arkitscenes_planes_bias_corrected.json")
    stitch = load("stitch_benchmark.json")["summary"]
    drift = load("drift_footprint.json")
    same = load("same_flat_plans.json")["walls_first"]
    damage = load("damage_sanity.json")
    walks = ("c00a170fe1", "1a8384c3f6", "c7d28f72c6")

    v = {c: video["walks"][c]["video"] for c in walks}
    gate_walls = [v[c]["gate_walls"]["within_3pct"] for c in walks]
    gw_in = sum(int(g.split("/")[0]) for g in gate_walls)
    gw_n = sum(int(g.split("/")[1]) for g in gate_walls)
    held = [v[c]["gate_walls"]["interval_holds_lidar"] for c in walks]
    held_in = sum(int(h.split("/")[0]) for h in held)
    held_n = sum(int(h.split("/")[1]) for h in held)
    pdims = [x for w in photo["walks"].values() for r in w["rooms"] for x in r["dimensions"]]
    p8 = sum(abs(x["error_pct"]) <= 8 for x in pdims)
    pheld = sum(x["holds"] for x in pdims)
    pfp = {c: w["footprint"] for c, w in photo["walks"].items()}
    ceil_rows = [w["pipeline"]["ceiling_error_mm"] for w in planes["walks"].values()]
    ceil_ok = sum(abs(e) <= 15 for e in ceil_rows)
    ceil_mean = sum(ceil_rows) / len(ceil_rows)

    timing = load("timing.json")["runs"]

    lines = [
        "# Benchmark report",
        "",
        "Generated by `bench/benchmark_report.py` from `bench/results/`. Methods and discussion are in "
        "[`bench/README.md`](../bench/README.md), gate definitions in [`docs/gates.md`](gates.md).",
        "",
        "**What the benchmark set is.**",
        "- Our three Stray Scanner walks of one flat (`c7d28f72c6` and `1a8384c3f6` cover the whole flat, "
        "`c00a170fe1` part of it). They are the input for all three tiers: the LiDAR data itself, its RGB stream as "
        "the video, and stills cut from it as per-room photo folders.",
        "- ARKitScenes: six walks in two venues with laser ground truth, for LiDAR floor and ceiling.",
        "- HouseLayout3D: 23 real buildings cut into rooms, for the stitch solver.",
        "",
        "**What is missing.** We had no tape or laser measurements of our own rooms, no staged damage, and no "
        "consumer-app capture. Video and photo accuracy is therefore measured against our LiDAR plans of the same "
        "walks, not against tape.",
        "",
        "## Gates at all three tiers",
        "",
        "| Gate | LiDAR | Video (vs LiDAR, same walk) | Photo (vs LiDAR, same rooms) |",
        "|---|---|---|---|",
        f"| Wall lengths (A-WALL-LIDAR ≤ max(2 cm, 1%); G-WALL-VIDEO ±3%; G-WALL-PHOTO ±8%) | Not measured (no tape) | "
        f"**{gw_in} of {gw_n}** gate walls within 3% (fail) | **{p8} of {len(pdims)}** box dimensions within 8% (fail) |",
        f"| Footprint vs reference | Same flat, two walks: {drift['same_flat']['on']['difference_pct']}% apart | "
        + " / ".join(f"{v[c]['footprint_m2']['error_pct']:+.1f}%" for c in walks) + " | "
        + " / ".join(f"{pfp[c]['error_pct']:+.0f}%" for c in pfp) + " |",
        f"| Ceiling height (G-CEIL ≤ 1.5 cm) | **{ceil_ok} of {len(ceil_rows)}** ARKitScenes walks within 15 mm, mean {ceil_mean:+.1f} mm "
        f"(code `{planes['code_commit']}`) (pass) | Not measured | Not measured |",
        "| Ceiling spread (G-CEIL-SPREAD ≤ 1 cm) | 10.1 mm and 43.9 mm on the two venues (fail) | — | — |",
        "| Opening widths (G-OPEN) | Not measured (no tape) | Not measured | Not measured |",
        f"| Stitched plan (G-PHOTO-STITCH, A-ADJ) | One connected map per walk | One connected map per walk | "
        + "; ".join(f"{c}: {w['stitch']['notes'].split(';')[0]}" for c, w in photo["walks"].items())
        + f". HouseLayout3D: all doors right in {stitch['exact']['all_doors_right']} noise-free runs, "
        f"{stitch['photo']['all_doors_right']} with photo-like noise (fail) |",
        f"| Calibration: nominal 90% interval holds (A-CALIB) | Ceiling interval carries the full 13 mm bias | "
        f"{held_in} of {held_n} paired gate walls (factor 4.5) | {pheld} of {len(pdims)} dimensions, both footprints (factor 5.1) |",
        "| Drift (G-DRIFT) | Method and on/off ablation (below) (pass) | Drift correction on; the declared-break variant is the fix loop | Not applicable |",
        f"| Damage (A-DMG-DETECT) | No staged damage: 0 false regions on our 3 walks; painted stains found in "
        f"{sum(w['painted_found'] for w in damage['walks'].values())} of {sum(w['painted_images'] for w in damage['walks'].values())} images | same detector | same detector |",
        "",
        "## Drift correction on and off (G-DRIFT, shipped LiDAR pipeline)",
        "",
        f"`bench/drift_footprint.py`, code `{drift['code_commit']}`.",
        "",
        "| Walk | Rooms, off → on | Footprint, off → on |",
        "|---|---|---|",
    ]
    for c in walks:
        w = drift["walks"][c]
        lines.append(f"| {c} | {w['off']['rooms']} → {w['on']['rooms']} | {w['off']['footprint_m2']} → {w['on']['footprint_m2']} m² |")
    s = drift["same_flat"]
    lines += [
        f"| **Same flat, two walks: footprint difference** | | {s['off']['difference_pct']}% → **{s['on']['difference_pct']}%** |",
        "",
        "With drift correction the two walks of the same flat agree more closely. Map sharpness and wall agreement "
        "(p90 5.99 → 2.78 cm between the two walks) are in `bench/README.md`.",
        "",
        "## Repeatability (same flat, walked twice, LiDAR)",
        "",
        "`bench/same_flat_plans.py`. Rooms of one walk are placed on the other by one rigid fit of their wall maps and "
        "paired by overlap. G-REPEAT asks every wall to agree within max(1 cm, 0.5%).",
        "",
        "| Room pair | IoU | Areas (m²) | Main-dimension differences (cm) |",
        "|---|---|---|---|",
    ]
    for p in same["pairs"]:
        lines.append(f"| A-R{p['room_a']} / B-R{p['room_b']} | {p['iou']} | {p['area_a']} / {p['area_b']} | "
                     f"{', '.join(str(d) for d in p['dimension_diffs_cm'])} |")
    lines += [
        "",
        f"Footprints {same['footprint_m2'][0]} / {same['footprint_m2'][1]} m² ({same['footprint_diff_pct']}% apart); "
        f"dimensions within the gate: {same['dimensions_within_1cm_or_0.5pct']}. **G-REPEAT is not met.** Where both walks saw a "
        "room's walls well (A-R4 / B-R4), it repeats within 0.6 cm. Differences come from rooms split differently: "
        "one walk rarely saw walls above 1.5 m. Ceiling repeatability is the G-CEIL-SPREAD row above.",
        "",
        "## Head-to-head against a consumer app",
        "",
        "| Room | Dimension | Tape | cozmo-scan (LiDAR) error | App error | Beat or tie |",
        "|---|---|---|---|---|---|",
        "| — | — | — | — | — | — |",
        "",
        "**Not done.** It needs two of our rooms captured with a consumer app, and a tape measure for the truth, and we "
        "had neither at the end. The plan for it:",
        "1. Capture with Polycam (free tier) and Stray Scanner in the same session.",
        "2. Tape every wall and opening.",
        "3. Export Polycam's floor plan.",
        "4. Compare dimension by dimension.",
        "",
        "## Timing (Apple M4, 16 GB)",
        "",
        "`bench/results/timing.json`: `cozmo run` on our captures.",
        "",
        "| Capture | Tier | Rooms | Pipeline time | Wall time with damage detection | Model outputs |",
        "|---|---|---|---|---|---|",
    ]
    for r in timing:
        lines.append(f"| {r['capture']} | {r['tier']} | {r['rooms']} | {r['pipeline_runtime_s']} s | {r['wall_s_with_damage']} s | "
                     f"{r['model_outputs']} |")
    cold = ROOT / "bench" / "results" / "timing_cold_video.json"
    if cold.is_file():
        t = json.loads(cold.read_text())
        lines.append(f"| {t['capture']} | video | {t['rooms']} | {t['pipeline_runtime_s']} s | {t['seconds']} s | live (cold cache) |")
        lines += ["", f"**Runtime.** LiDAR and photo runs are live and take seconds to a few minutes. A cold video run takes about "
                  f"10 s per second of video ({t['seconds']} s for a 37 s clip), so a 3-minute walkthrough would need about "
                  f"30 minutes, over A-RUNTIME (10 min). **Determinism:** cached runs replay exactly; a fresh DA3 run on Apple's "
                  f"GPU is not bit-identical, and the cold run above gave {t['rooms']} rooms and {t['footprint_m2']} m² against "
                  f"{t['cached_run']['rooms']} rooms and {t['cached_run']['footprint_m2']} m² from the cache.", ""]
    (ROOT / "docs" / "benchmark_report.md").write_text("\n".join(lines))
    print("wrote docs/benchmark_report.md")


if __name__ == "__main__":
    main()
